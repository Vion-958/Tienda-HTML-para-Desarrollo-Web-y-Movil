"""Persistencia: PostgreSQL si Vault entrega database_url, si no SQLite. Mismo SQL en ambos."""

import os
import re
import sqlite3
import threading
import zlib
from contextlib import contextmanager
from decimal import Decimal
from pathlib import Path

from comun.bitacora import evento, logger

AHORA = "to_char(now() at time zone 'utc', 'YYYY-MM-DD HH24:MI:SS')"
_TABLA = re.compile(r"^\s*(UPDATE)\s+(\w+)|^\s*(SELECT|INSERT|DELETE)\b.*?\b(?:FROM|INTO)\s+(\w+)", re.I | re.S)
_INSERT = re.compile(r"^\s*INSERT\s+INTO\s+(\w+)", re.I)


def _pg(sql: str, con_parametros: bool) -> str:
    """Traduce el dialecto SQLite usado en los servicios a PostgreSQL."""
    if con_parametros:
        sql = sql.replace("%", "%%").replace("?", "%s")
    sql = sql.replace("datetime('now')", AHORA)
    # pedido_items no se actualiza: ctid conserva el orden de insercion como rowid.
    sql = re.sub(r"\bORDER BY rowid\b", "ORDER BY ctid", sql)
    return re.sub(r"\bLIKE\b", "ILIKE", sql)


def _ddl(script: str) -> str:
    script = re.sub(r"(?im)^\s*PRAGMA[^;]*;", "", script)
    script = script.replace("INTEGER PRIMARY KEY AUTOINCREMENT", "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
    script = re.sub(r"\bINTEGER\b", "BIGINT", script)
    script = re.sub(r"\bREAL\b", "DOUBLE PRECISION", script)
    script = re.sub(r"\bBLOB\b", "BYTEA", script)
    script = script.replace(" COLLATE NOCASE", "").replace("datetime('now')", AHORA)
    return re.sub(r"\bchar\(", "chr(", script)


def _valor(v):
    if isinstance(v, Decimal):
        return int(v) if v == v.to_integral_value() else float(v)
    if isinstance(v, memoryview):
        return bytes(v)
    return v


class Fila:
    """Igual que sqlite3.Row: fila["col"], fila[0], dict(fila)."""

    __slots__ = ("_nombres", "_valores")

    def __init__(self, nombres, valores):
        self._nombres, self._valores = nombres, valores

    def keys(self):
        return list(self._nombres)

    def __getitem__(self, k):
        return self._valores[k] if isinstance(k, int) else self._valores[self._nombres.index(k)]

    def __iter__(self):
        return iter(self._valores)

    def __len__(self):
        return len(self._valores)


def _fabrica(cursor):
    nombres = [c.name for c in cursor.description or []]
    return lambda valores: Fila(nombres, [_valor(v) for v in valores])


class _Cursor:
    def __init__(self, cur, lastrowid=None):
        self._cur, self.lastrowid = cur, lastrowid

    @property
    def rowcount(self):
        return self._cur.rowcount

    def fetchone(self):
        return self._cur.fetchone() if self._cur.description else None

    def fetchall(self):
        return self._cur.fetchall() if self._cur.description else []

    def __iter__(self):
        return iter(self.fetchall())


class Conexion:
    """Envuelve sqlite3 o psycopg y deja en el log cada consulta a la base."""

    def __init__(self, base: "BaseDatos", con):
        self.base, self.con = base, con

    def _registrar(self, sql: str, filas: int):
        m = _TABLA.match(sql)
        if not m:
            return
        accion, tabla = (m.group(1), m.group(2)) if m.group(1) else (m.group(3), m.group(4))
        if accion.upper() == "SELECT" and not self.base.log_lecturas:
            return
        evento("BD %s %s: %s %s (%s filas)", self.base.motor, self.base.nombre, accion.upper(), tabla, filas)

    def execute(self, sql: str, params=()):
        if self.base.motor == "sqlite":
            cur = self.con.execute(sql, params)
            self._registrar(sql, cur.rowcount if cur.rowcount >= 0 else "-")
            return cur
        m = _INSERT.match(sql)
        devuelve_id = bool(m) and m.group(1) in self.base.con_identidad and "RETURNING" not in sql.upper()
        q = _pg(sql + (" RETURNING id" if devuelve_id else ""), bool(params))
        cur = self.con.cursor(row_factory=_fabrica)
        cur.execute(q, tuple(params) if params else None)
        self._registrar(sql, cur.rowcount)
        return _Cursor(cur, cur.fetchone()[0] if devuelve_id else None)

    def executemany(self, sql: str, filas):
        filas = list(filas)
        if self.base.motor == "sqlite":
            cur = self.con.executemany(sql, filas)
        else:
            cur = self.con.cursor()
            cur.executemany(_pg(sql, True), filas)
        self._registrar(sql, len(filas))
        return cur

    def executescript(self, script: str):
        if self.base.motor == "sqlite":
            return self.con.executescript(script)
        return self.con.execute(_ddl(script))


class BaseDatos:
    def __init__(self, ruta: str, esquema: Path, datos_iniciales: Path | None = None, url=None, nombre: str = ""):
        """url: texto o funcion(forzar) que la lee desde Vault; se relee si la clave de la base cambia."""
        self.nombre = nombre or Path(ruta).stem
        if nombre:
            logger(nombre)
        self._fuente = url if callable(url) else (lambda forzar=False: url)
        self.url, self.ruta = self._fuente(), ruta
        self.motor = "postgres" if self.url else "sqlite"
        # DB_LOG=escrituras deja fuera los SELECT del log.
        self.log_lecturas = os.getenv("DB_LOG", "todo") != "escrituras"
        self.con_identidad: set[str] = set()
        self._libres: list = []
        self._lock = threading.Lock()
        self._llave = zlib.crc32(self.nombre.encode())
        self._memoria = None
        if self.motor == "sqlite":
            nueva = ruta == ":memory:" or not Path(ruta).exists()
            if ruta != ":memory:":
                Path(ruta).parent.mkdir(parents=True, exist_ok=True)
            else:
                self._memoria = sqlite3.connect(ruta, check_same_thread=False, isolation_level=None)
            with self.conexion() as con:
                con.executescript(esquema.read_text(encoding="utf-8"))
                if nueva and datos_iniciales and datos_iniciales.exists():
                    con.executescript(datos_iniciales.read_text(encoding="utf-8"))
        else:
            self._preparar_pg(esquema, datos_iniciales)
        evento("BD %s %s: lista (%s)", self.motor, self.nombre, self.destino)

    @property
    def destino(self) -> str:
        if self.motor == "sqlite":
            return self.ruta
        return re.sub(r"//[^@]*@", "//", self.url) + f", esquema {self.nombre}"  # sin usuario ni clave

    def _preparar_pg(self, esquema: Path, datos_iniciales: Path | None):
        with self.conexion() as c:
            c.con.execute("SELECT pg_advisory_lock(%s)", (self._llave,))
            try:
                c.executescript(esquema.read_text(encoding="utf-8"))
                c.con.execute("CREATE TABLE IF NOT EXISTS _semilla (cargada BIGINT)")
                if not c.con.execute("SELECT 1 FROM _semilla").fetchone():
                    if datos_iniciales and datos_iniciales.exists():
                        c.executescript(datos_iniciales.read_text(encoding="utf-8"))
                    c.con.execute("INSERT INTO _semilla VALUES (1)")
                filas = c.con.execute("SELECT table_name FROM information_schema.columns WHERE table_schema = current_schema()"
                                      " AND column_name = 'id' AND is_identity = 'YES'").fetchall()
                self.con_identidad = {f[0] for f in filas}
                for tabla in self.con_identidad:
                    # Los datos de prueba traen ids fijos: la secuencia sigue desde el mayor.
                    c.con.execute(f"SELECT setval(pg_get_serial_sequence('{tabla}', 'id'), "
                                  f"GREATEST((SELECT COALESCE(MAX(id), 0) FROM {tabla}), 1))")
            finally:
                c.con.execute("SELECT pg_advisory_unlock(%s)", (self._llave,))

    def _abrir(self):
        if self.motor == "sqlite":
            if self._memoria is not None:
                return self._memoria
            con = sqlite3.connect(self.ruta, timeout=10, isolation_level=None)
            con.execute("PRAGMA journal_mode=WAL")
            con.row_factory = sqlite3.Row
            con.execute("PRAGMA foreign_keys=ON")
            return con
        import psycopg
        while True:
            with self._lock:
                con = self._libres.pop() if self._libres else None
            if con is None:
                break
            try:
                con.execute("SELECT 1")
                return con
            except psycopg.Error:
                con.close()  # conexion cortada por el servidor
        try:
            return psycopg.connect(self.url, autocommit=True, connect_timeout=5)
        except psycopg.OperationalError:
            nueva = self._fuente(True)
            if not nueva or nueva == self.url:
                raise
            evento("BD postgres %s: credencial de la base renovada desde Vault", self.nombre)
            self.url = nueva
            return psycopg.connect(self.url, autocommit=True, connect_timeout=5)

    def _devolver(self, con):
        if self.motor == "sqlite":
            if self._memoria is None:
                con.close()
            return
        if con.closed or con.info.transaction_status != 0:
            con.close()
            return
        with self._lock:
            if len(self._libres) < 10:
                self._libres.append(con)
                return
        con.close()

    @contextmanager
    def conexion(self):
        con = self._abrir()
        if self.motor == "sqlite":
            con.row_factory = sqlite3.Row
        try:
            yield Conexion(self, con)
        finally:
            self._devolver(con)

    @contextmanager
    def transaccion(self):
        """Escrituras en serie por servicio: BEGIN IMMEDIATE en SQLite, bloqueo consultivo en PostgreSQL."""
        with self.conexion() as c:
            if self.motor == "sqlite":
                c.con.execute("BEGIN IMMEDIATE")
                try:
                    yield c
                    c.con.execute("COMMIT")
                except Exception:
                    c.con.execute("ROLLBACK")
                    raise
            else:
                with c.con.transaction():
                    c.con.execute("SELECT pg_advisory_xact_lock(%s)", (self._llave,))
                    yield c
